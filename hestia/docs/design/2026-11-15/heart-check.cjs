const assert = require('node:assert/strict');
const fs = require('fs');
const { chromium } = require('/Users/david.meguira/.npm/_npx/e41f203b7505f1fb/node_modules/playwright');
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome' });
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } });
  const errors = [], checks = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.addInitScript(() => localStorage.setItem('hestia-language', 'fr'));
  await page.goto('http://127.0.0.1:1422/#/crew/1');
  const heart = page.getByRole('button', { name: /^Cœur:/ }).last();
  await heart.click();
  await page.getByRole('heading', { name: 'Cœur', exact: true }).waitFor();
  const organ = page.locator('.hz-organ-heart');
  const motion = await organ.evaluate(element => {
    const style = getComputedStyle(element);
    return { duration: style.animationDuration, iterations: style.animationIterationCount, size: element.parentElement.getAttribute('width'), frames: element.getAnimations()[0]?.effect.getKeyframes() };
  });
  assert.equal(motion.duration, '0.68s'); assert.equal(motion.iterations, '1'); assert.equal(motion.size, '29');
  assert(motion.frames.every(frame => Object.keys(frame).every(key => ['offset', 'computedOffset', 'easing', 'composite', 'transform'].includes(key))));
  await organ.evaluate(element => Promise.all(element.getAnimations().map(animation => animation.finished)));
  assert.equal(await organ.evaluate(element => element.getAnimations().filter(animation => animation.playState === 'running').length), 0);
  const hit = heart.locator('.hz-zone-label-hit');
  assert.equal(await hit.evaluate(element => getComputedStyle(element).stroke), 'rgba(0, 0, 0, 0)');
  assert.equal(await hit.evaluate(element => getComputedStyle(element).fill), 'rgba(0, 0, 0, 0)');
  checks.push('heart is 29 units, filled, one finite 680 ms transform animation; no pointer selection frame');
  const readings = page.locator('.hz-heart-readings .hz-zone-reading');
  for (const width of [1024, 1280, 1440]) {
    await page.setViewportSize({width, height: 900});
    const boxes = await readings.evaluateAll(elements => elements.map(element => ({ y: element.getBoundingClientRect().y, x: element.getBoundingClientRect().x })));
    assert.equal(boxes.length, 3); assert(boxes.every(box => box.y === boxes[0].y));
    assert(boxes[1].x > boxes[0].x && boxes[2].x > boxes[1].x);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  }
  checks.push('three measurements in one row at 1024, 1280 and 1440; no document overflow');
  await page.setViewportSize({width:1280,height:800});
  await page.screenshot({path:'/private/tmp/hestia-interaction-review/heart-desktop-fr.png',animations:'disabled'});
  await page.locator('.hz-profile-health').screenshot({path:'/private/tmp/hestia-interaction-review/heart-detail-fr.png',animations:'disabled'});
  await heart.press('Tab'); await page.keyboard.press('Shift+Tab');
  assert.equal(await heart.evaluate(element => element.matches(':focus-visible')), true);
  assert.equal(await hit.evaluate(element => getComputedStyle(element).strokeWidth), '1.6px');
  assert.notEqual(await hit.evaluate(element => getComputedStyle(element).stroke), 'rgba(0, 0, 0, 0)');
  await page.keyboard.press('Enter');
  await page.screenshot({path:'/private/tmp/hestia-interaction-review/heart-keyboard-fr.png',animations:'disabled'});
  checks.push('keyboard focus stays visible and Enter selects the heart');
  await page.emulateMedia({reducedMotion:'reduce'});
  assert.equal(await organ.evaluate(element => getComputedStyle(element).animationName), 'none');
  checks.push('reduced motion disables the heart animation');
  const mobile = await browser.newPage({ viewport:{width:390,height:844},isMobile:true,hasTouch:true });
  mobile.on('pageerror', error => errors.push(error.message));
  await mobile.addInitScript(() => localStorage.setItem('hestia-language','fr'));
  await mobile.goto('http://127.0.0.1:8011/crew/');
  await mobile.getByRole('button',{name:/Alex Mercer/}).click();
  await mobile.getByRole('button',{name:/^Cœur:/}).last().click();
  const dialog = mobile.getByRole('dialog'); await dialog.waitFor();
  assert.equal(await dialog.locator('.hz-heart-readings .hz-zone-reading').count(),3);
  await mobile.screenshot({path:'/private/tmp/hestia-interaction-review/heart-mobile-fr.png',animations:'disabled'});
  await mobile.keyboard.press('Escape'); assert.equal(await dialog.count(),0);
  checks.push('mobile heart detail opens, keeps three readings and closes');
  assert.equal(errors.length,0);
  fs.writeFileSync('/private/tmp/hestia-interaction-review/heart-checks.json',JSON.stringify({checks,motion,errors},null,2));
  console.log(JSON.stringify({checks,errors},null,2));
  await browser.close();
})().catch(error => { console.error(error);process.exit(1); });
